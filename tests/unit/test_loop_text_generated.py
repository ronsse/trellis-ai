"""The shipped loop-text files are exactly what ``trellis_wire.loop_text`` renders.

``system.md``, ``claude-md.md``, ``agent-rule.md`` and the ``trellis-loop``
``SKILL.md`` are package data the CLI reads, so they stay checked in, but they
are generated by ``scripts/generate_loop_text.py`` and only that script changes
them. This is the drift test, in the spirit of ``openapi-check``: edit a file by
hand, or edit a fragment without running the script, and it fails.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path
from types import ModuleType

import pytest

SCRIPT = Path(__file__).resolve().parents[2] / "scripts" / "generate_loop_text.py"


def _load_script() -> ModuleType:
    spec = importlib.util.spec_from_file_location("generate_loop_text", SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


GENERATOR = _load_script()


def test_the_generator_covers_every_shipped_loop_file() -> None:
    names = sorted(p.name for p in GENERATOR.generated_files())
    assert names == [
        "SKILL.md",
        "agent-rule.md",
        "claude-md.md",
        "system.md",
    ]  # hand-read: 4


@pytest.mark.parametrize("path", sorted(GENERATOR.generated_files()))
def test_a_generated_file_equals_the_source_render(path: Path) -> None:
    assert path.read_text(encoding="utf-8") == GENERATOR.generated_files()[path]


def test_nothing_is_stale() -> None:
    assert GENERATOR.stale_files() == []


def test_a_hand_edit_is_detected(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The check bites: a copy of the tree with one edited file reports it stale."""
    files = GENERATOR.generated_files()
    victim = next(iter(files))
    copy = tmp_path / victim.name
    copy.write_text(files[victim] + "drift\n", encoding="utf-8")
    monkeypatch.setattr(GENERATOR, "generated_files", lambda: {copy: files[victim]})
    assert GENERATOR.stale_files() == [copy]
    assert GENERATOR.main(["--check"]) == 1
