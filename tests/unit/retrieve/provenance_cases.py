def sections() -> list[dict[str, Any]]:
    """Two sections over the same made-up items."""
    items = flat_items()
    return [
        {"name": "Background", "items": items[:2]},
        {"name": "Details", "items": items[2:]},
    ]


def render_all(**kwargs: Any) -> dict[str, str]:
    """Every rendering the golden file pins, keyed by case name.

    ``kwargs`` are passed to all three formatters, so the off-identical
    test can call this with no flag and the on test with ``provenance_line``.
    """
    items = flat_items()
    return {
        "flat_roomy": format_pack_as_markdown(
            items, "warm the widget cache", max_tokens=2000, pack_id=PACK_ID, **kwargs
        ),
        "flat_tight": format_pack_as_markdown(
            items, "warm the widget cache", max_tokens=90, pack_id=PACK_ID, **kwargs
        ),
        "flat_starved": format_pack_as_markdown(
            items, "warm the widget cache", max_tokens=20, pack_id=PACK_ID, **kwargs
        ),
        # The index renderer takes no provenance argument: an index line is
        # a pointer, and the line is only for items shown with a body.
        "index": format_pack_as_index_markdown(
            items, "warm the widget cache", max_tokens=2000, pack_id=PACK_ID
        ),
        "sectioned_roomy": format_sectioned_pack_as_markdown(
            sections(),
            "warm the widget cache",
            max_tokens=2000,
            pack_id=PACK_ID,
            **kwargs,
        ),
        "sectioned_tight": format_sectioned_pack_as_markdown(
            sections(),
            "warm the widget cache",
            max_tokens=110,
            pack_id=PACK_ID,
            **kwargs,
        ),
    }
